interface Props {
  onClose: () => void
}

export function ImageStudioGuide({ onClose }: Props): JSX.Element {
  return <Dialog title="Что умеет студия картинок" size="lg" onClose={onClose} padded>
    <div className="image-studio-guide">
      <p className="image-studio-guide-lead">
        Студия — это галерея разговора: всё, что нарисовал ассистент или принесли вы, лежит здесь и разбирается на месте.
        Ниже — все возможности по разделам, со снимками экрана.
      </p>
      <nav className="image-studio-guide-toc" aria-label="Разделы справочника">
        {IMAGE_STUDIO_GUIDE.map((section) => (
          <a key={section.id} href={`#guide-${section.id}`}>{section.title}</a>
        ))}
      </nav>
      {IMAGE_STUDIO_GUIDE.map((section) => (
        <section key={section.id} id={`guide-${section.id}`} className="image-studio-guide-section" aria-labelledby={`guide-title-${section.id}`}>
          <h3 id={`guide-title-${section.id}`}>{section.title}</h3>
          <p className="image-studio-guide-lead">{section.lead}</p>
          {section.shot && (
            // Снимки грузятся лениво: справочник открывают редко, а весит он
            // больше половины мегабайта.
            <img className="image-studio-guide-shot" loading="lazy" src={section.shot.src} alt={section.shot.alt} />
          )}
          <ul>
            {section.items.map((item) => <li key={item}>{item}</li>)}
          </ul>
        </section>
      ))}
    </div>
  </Dialog>
}
