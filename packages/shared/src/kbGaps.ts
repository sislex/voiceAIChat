// Пробелы базы знаний: вопрос, на который база не ответила (или ответила
// неполно), и ответ, который модель потом нашла в коде либо получила в ходе
// разработки. Пробел обязан стать записью в базе — иначе следующий ход снова
// задаст базе тот же вопрос и снова заплатит за исследование кода, то есть
// ровно ту стоимость, которую база знаний и должна снимать.
//
// Договорённость с моделью такая же, как с уточняющими вопросами
// (questions.ts): fenced-блок в конце ответа. Разбор — чистая функция, поэтому
// ею пользуются и CI-раннер (работа модели, fix-loop), и тесты.

/** Один пробел базы знаний, о котором сообщила модель. */
export interface KbGapNote {
  /** О чём спрашивали базу знаний (вопрос или тема). */
  question: string
  /** Что выяснилось по коду или по итогам разработки. */
  answer: string
  /** Куда писать: тема `docs/kb/*.md` либо заголовок статьи (необязательно). */
  topic?: string
}

/** Язык fenced-блока, в котором модель перечисляет пробелы. */
export const KB_GAPS_FENCE = 'kb-gaps'

/**
 * Кап на ход: больше десятка «пробелов» — это уже пересказ работы, а не пробелы
 * базы. Промпт шага актуализации от такого списка распухает, а записи мельчают.
 */
export const MAX_KB_GAPS = 10

/** Капы полей: вопрос — строкой, ответ — абзацем; остальное в промпте шум. */
const QUESTION_CAP = 300
const ANSWER_CAP = 1500
const TOPIC_CAP = 120

/**
 * Правило, которое делает пробел базы знаний долгом, а не тупиком. Живёт рядом
 * с разбором блока: формулировка в промпте и механика записи расходиться не
 * должны. Текст общий для хода чата и хода CI-рана — конкретный способ записи
 * дописывает вызывающий (`kbToolHint` в этом же пакете, `kbRunDirective` на
 * сервере).
 */
export const KB_GAP_RULE = [
  'Обращение к базе знаний без ответа или с неполным ответом — это долг перед базой, а не тупик.',
  'Нашёл ответ в коде или получил его в ходе разработки — занеси недостающие сведения в тот раздел',
  'базы знаний, где их искал: дополни существующий раздел, а не заводи второй про то же.',
  'В базу идёт только проверенное по коду — предположения, планы и «похоже, что» не записывай.'
].join(' ')

/**
 * Формат блока для ходов, где в базу пишет не модель, а шаг воркфлоу: модель
 * называет пробел и ответ, запись делает шаг «Актуализировать базу знаний».
 */
export const KB_GAPS_HINT = [
  'Пробелы базы знаний перечисли в самом конце ответа fenced-блоком с JSON-массивом:',
  '```' + KB_GAPS_FENCE,
  '[{"question":"о чём спрашивал базу","answer":"что выяснилось по коду","topic":"ci-runner"}]',
  '```',
  'Один элемент — один вопрос, на который база не ответила или ответила неполно, и проверенный',
  'ответ к нему; `topic` — тема `docs/kb/*.md` или заголовок статьи (необязательно). Блок забирает',
  'шаг «Актуализировать базу знаний»: он и внесёт эти сведения в базу. Пробелов не было — блока',
  'не добавляй, догадки в него не пиши.'
].join('\n')

const FENCE_RE = /```kb-gaps[^\S\n]*\n([\s\S]*?)```[^\S\n]*/

/** Одна строка на поле: перевод строки в промпте шага только рвёт список. */
function clamp(value: string, cap: number): string {
  const flat = value.trim().replace(/\s+/g, ' ')
  return flat.length > cap ? `${flat.slice(0, cap)}…` : flat
}

/** Валидация одного пробела (терпим к мусору от модели). */
function toGap(v: unknown): KbGapNote | null {
  if (!v || typeof v !== 'object') return null
  const o = v as { question?: unknown; answer?: unknown; topic?: unknown }
  if (typeof o.question !== 'string' || !o.question.trim()) return null
  // Пробел без ответа — жалоба, а не знание: заносить в базу нечего.
  if (typeof o.answer !== 'string' || !o.answer.trim()) return null
  const topic = typeof o.topic === 'string' && o.topic.trim() ? clamp(o.topic, TOPIC_CAP) : undefined
  return {
    question: clamp(o.question, QUESTION_CAP),
    answer: clamp(o.answer, ANSWER_CAP),
    ...(topic ? { topic } : {})
  }
}

/**
 * Ищет в тексте ответа блок ```kb-gaps``` и разбирает его. Пустой массив —
 * блока нет, JSON битый или все элементы негодные: пробелов не сообщали.
 * Дубли по вопросу схлопываются здесь же: две записи об одном и том же — самый
 * дорогой способ испортить базу.
 */
export function parseKbGaps(text: string): KbGapNote[] {
  const m = FENCE_RE.exec(text)
  if (!m) return []
  let raw: unknown
  try {
    raw = JSON.parse(m[1])
  } catch {
    return []
  }
  if (!Array.isArray(raw)) return []
  const seen = new Set<string>()
  const gaps: KbGapNote[] = []
  for (const item of raw) {
    const gap = toGap(item)
    if (!gap) continue
    const key = gap.question.toLowerCase()
    if (seen.has(key)) continue
    seen.add(key)
    gaps.push(gap)
    if (gaps.length >= MAX_KB_GAPS) break
  }
  return gaps
}
