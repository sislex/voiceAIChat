// Пользовательский ввод → выражение MATCH для FTS5. Отдельный модуль без БД,
// чтобы экранирование проверялось чистыми тестами (в том числе fuzz-ом).

/** Слово запроса: буквы/цифры/подчёркивание в любом алфавите. */
const TOKEN_RE = /[\p{L}\p{N}_]+/gu
/** Ввод закончился на середине слова — последнее слово ищем как префикс. */
const OPEN_TAIL_RE = /[\p{L}\p{N}_]$/u
/** Больше слов в запрос не пускаем: пользы нет, а FTS считает каждое. */
const MAX_TOKENS = 16
/** Одно слово длиннее этого — обрезаем (защита от вставленной «стены текста»). */
const MAX_TOKEN_LEN = 64
/** Со слова короче двух символов префиксный поиск даёт полбазы — не включаем. */
const MIN_PREFIX_LEN = 2

/**
 * Собирает безопасное выражение MATCH: каждое слово уходит в кавычках, поэтому
 * синтаксис FTS5 из пользовательского ввода (`"`, `*`, `NEAR`, `-`, `^`, `:`,
 * скобки) не может ни изменить смысл запроса, ни уронить его ошибкой парсера:
 * кавычки превращают всё это в обычный текст, а служебных символов внутри
 * токенов не остаётся — они не проходят TOKEN_RE.
 *
 * Последнее слово получает `*` (поиск по началу), если пользователь не поставил
 * после него разделитель: так поиск на ходу находит «миграцию» уже по «мигра».
 *
 * Пустая строка на выходе — искать нечего (ввод без слов); вызывающий обязан
 * вернуть пустой результат, а не выполнять MATCH ''.
 */
export function toFtsMatchQuery(raw: string): string {
  const tokens = (raw.match(TOKEN_RE) ?? []).slice(0, MAX_TOKENS).map((t) => t.slice(0, MAX_TOKEN_LEN))
  if (tokens.length === 0) return ''
  const openTail = OPEN_TAIL_RE.test(raw)
  return tokens
    .map((token, i) => {
      const phrase = `"${token}"`
      const isLast = i === tokens.length - 1
      return isLast && openTail && token.length >= MIN_PREFIX_LEN ? `${phrase}*` : phrase
    })
    .join(' AND ')
}
