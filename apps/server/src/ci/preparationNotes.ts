// Заметка о дизайне для промпта подготовки. Вынесена из server.ts, потому что
// запуск подготовки в тесте требует реального CLI, а текст заметки — чистая
// функция от связей задачи и собранных make-источников.
import type { TaskDesignLink } from '@voicechat/shared'
import type { LlmMakeSource } from '@voicechat/shared'

/**
 * Что сказать модели подготовки про дизайн задачи.
 *
 * Главный сценарий — задача из Make-чата: файлы макета доступны read-only
 * инструментами make-источника, и модель обязана читать их, а не открывать
 * опубликованную страницу по URL (изнутри рана она не открывается, и модель
 * задавала вопрос «критичный источник истины недоступен»).
 *
 * Связь есть, а источников нет — конфигурация без Make MCP: об этом говорим
 * прямо, чтобы вопрос модели был про недоступность, а не про поиск URL.
 */
export function preparationDesignNote(designs: readonly TaskDesignLink[], sources: readonly LlmMakeSource[]): string {
  if (!designs.length) return ''
  if (!sources.length) {
    return 'Дизайн задачи привязан к Make-проекту, но инструменты Make в этой конфигурации недоступны: считай источник дизайна недоступным и не ищи опубликованную страницу по URL.'
  }
  const list = sources
    .map((source) => `${source.name} (mcp__${source.name}__make_list_files / mcp__${source.name}__make_read_file${source.mode === 'files' ? `; файлы: ${source.paths.join(', ')}` : '; весь проект'})`)
    .join('; ')
  return `Дизайн задачи: макет лежит в Make-проекте и доступен read-only инструментами — ${list}. Это источник истины по дизайну, состояниям и адаптивности: читай файлы инструментами, опубликованную страницу по URL открывать не нужно и не из чего.`
}
